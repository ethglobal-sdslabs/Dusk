import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]

for (const [contract, exportName, file] of [
  ['DuskIdentityController', 'DuskIdentityControllerAbi', 'controller-abi.ts'],
  ['DuskAdmission', 'DuskAdmissionAbi', 'admission-abi.ts'],
  ['DuskReputation', 'DuskReputationAbi', 'reputation-abi.ts'],
] as const) {
  const out = new URL(`../contracts/out/${contract}.sol/${contract}.json`, import.meta.url)
  const { abi } = JSON.parse(readFileSync(out, 'utf8')) as { abi: unknown[] }
  writeFileSync(
    new URL(`../packages/ens/src/${file}`, import.meta.url),
    '// Generated by scripts/gen-ens-abi.ts from contracts/out (forge build). Do not edit.\n' +
      `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const\n`,
  )
}
if (!dir) process.exit(0)

const WANT: Record<string, { file: string; items: string[] }> = {
  ETHRegistryAbi: {
    file: 'ETHRegistry.json',
    items: ['getParent', 'getResolver', 'getState', 'getSubregistry', 'roles', 'supportsInterface', 'hasRootRoles', 'setSubregistry', 'ownerOf'],
  },
  UserRegistryAbi: {
    file: 'UserRegistryImpl.json',
    items: [
      'initialize', 'getParent', 'setParent', 'getResolver', 'getState', 'getSubregistry', 'register', 'unregister', 'renew',
      'roles', 'hasRootRoles', 'grantRootRoles', 'revokeRootRoles', 'ownerOf', 'latestOwnerOf', 'safeTransferFrom',
      'LabelRegistered', 'LabelUnregistered', 'ExpiryUpdated', 'TransferDisallowed', 'LabelAlreadyRegistered', 'EACUnauthorizedAccountRoles',
      'ERC1155InvalidReceiver', 'LabelAlreadyReserved', 'LabelExpired', 'CannotSetPastExpiry', 'CannotReduceExpiry',
    ],
  },
  PermissionedResolverAbi: {
    file: 'PermissionedResolverImpl.json',
    items: ['initialize', 'setText', 'setAddress', 'multicall', 'resolve', 'roles', 'hasRootRoles', 'grantRootRoles', 'upgradeToAndCall', 'EACUnauthorizedAccountRoles'],
  },
  VerifiableFactoryAbi: {
    file: 'VerifiableFactory.json',
    items: ['deployProxy', 'predictProxyAddress', 'ProxyDeployed'],
  },
}

type Item = { type: string; name?: string }
let out =
  '// Generated by scripts/gen-ens-abi.ts from ensdomains/contracts-v2 @ 07e55a05,\n' +
  '// contracts/deployments/sepolia (the live 2026-10-01 Sepolia deployment). Do not edit.\n'
for (const [exportName, { file, items }] of Object.entries(WANT)) {
  const abi = (JSON.parse(readFileSync(join(dir, file), 'utf8')) as { abi: Item[] }).abi
  const picked = abi.filter((x) => x.name !== undefined && items.includes(x.name) && ['function', 'event', 'error'].includes(x.type))
  const missing = items.filter((n) => !picked.some((x) => x.name === n))
  if (missing.length) throw new Error(`${file} has no ${missing.join(', ')}`)
  out += `export const ${exportName} = ${JSON.stringify(picked, null, 2)} as const\n\n`
}

const target = new URL('../packages/ens/src/abi.ts', import.meta.url)
const current = readFileSync(target, 'utf8')
const v1 = current.slice(current.indexOf('export const ENSV1RegistryAbi'))
if (!v1.startsWith('export const ENSV1RegistryAbi')) throw new Error('abi.ts lost its ENSV1RegistryAbi block')
writeFileSync(target, out + v1)
